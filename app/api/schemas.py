from typing import List, Optional
from pydantic import BaseModel, Field

class QueryRequest(BaseModel):
    question: str = Field(..., description="Natural language question to ask the documentation assistant.", min_length=2)
    session_id: Optional[str] = Field(None, description="Optional session ID for conversation memory and follow-up questions.")

class SourceCitation(BaseModel):
    source: str
    section: Optional[str] = None
    snippet: Optional[str] = None

class QueryResponse(BaseModel):
    question: str
    answer: str
    sources: List[SourceCitation]
    query_type: Optional[str] = None
    retries_used: int = 0
    web_fallback_used: bool = False
    is_grounded: Optional[bool] = True
    session_id: Optional[str] = None
    execution_time_sec: float

class IngestUrlsRequest(BaseModel):
    urls: List[str] = Field(..., min_length=1, description="List of documentation URLs to scrape and index.")

class IngestResponse(BaseModel):
    message: str
    documents_processed: List[str]
    total_chunks_added: int

class DocumentSummary(BaseModel):
    source: str
    chunks_count: int
    sections: List[str] = []

class DocumentsListResponse(BaseModel):
    total_documents: int
    total_chunks: int
    documents: List[DocumentSummary]

class FeedbackRequest(BaseModel):
    query: str = Field(..., description="The query that produced the answer.")
    answer: str = Field(..., description="The answer generated by the assistant.")
    rating: str = Field(..., description="Thumbs rating: 'up' or 'down'.")
    comment: Optional[str] = Field(None, description="Optional user comment or correction.")

class FeedbackResponse(BaseModel):
    message: str
    feedback_id: str
    status: str = "success"
